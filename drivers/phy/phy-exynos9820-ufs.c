static int exynos9820_phy_wait_for_calibration(struct phy *phy, u8 lane)
{
	log_debug("%s: waitomg on lane %u ...\n", __func__, lane);
	udelay(0xC8);
	struct samsung_ufs_phy *ufs_phy = get_samsung_ufs_phy(phy);
	return 0;
}
	

